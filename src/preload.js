const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('rift', {
  toggleOverlay: () => ipcRenderer.send('overlay:toggle'),
  hideOverlay: () => ipcRenderer.send('overlay:hide'),
  moveOverlay: (position) => ipcRenderer.send('overlay:move', position),
  startOverlayDrag: () => ipcRenderer.invoke('overlay:drag-start'),
  resizeOverlay: (size) => ipcRenderer.send('overlay:resize', size),
  updateOverlay: (snapshot) => ipcRenderer.send('overlay:update', snapshot),
  showOverlayTooltip: (data) => ipcRenderer.send('overlay:tooltip-show', data),
  hideOverlayTooltip: () => ipcRenderer.send('overlay:tooltip-hide'),
  selectOverlayChampion: (data) => ipcRenderer.send('overlay:champion-select', data),
  selectOverlayBuildStage: (stage) => ipcRenderer.send('overlay:build-stage-select', stage),
  selectOverlayBuildChoice: (choice) => ipcRenderer.send('overlay:build-choice', choice),
  onOverlayBuildChoice: (callback) => ipcRenderer.on('overlay:build-choice', (_event, choice) => callback(choice)),
  toggleAramAugmentFromOverlay: (augmentId) => ipcRenderer.send('overlay:augment-toggle', augmentId),
  onOverlayAugmentToggle: (callback) => ipcRenderer.on('overlay:augment-toggle', (_event, augmentId) => callback(augmentId)),
  returnToLiveRoster: () => ipcRenderer.send('overlay:return-live'),
  onOverlayReturnLive: (callback) => ipcRenderer.on('overlay:return-live', () => callback()),
  onTooltipContent: (callback) => ipcRenderer.on('tooltip:content', (_event, html) => callback(html)),
  reportTooltipSize: (size) => ipcRenderer.send('tooltip:measure', size),
  setTooltipPointerInside: (inside) => ipcRenderer.send('tooltip:pointer-state', inside === true),
  onOverlayChampionSelect: (callback) => ipcRenderer.on('overlay:champion-select', (_event, data) => callback(data)),
  onOverlayBuildStageSelect: (callback) => ipcRenderer.on('overlay:build-stage-select', (_event, stage) => callback(stage)),
  toggleGuideFromLauncher: () => ipcRenderer.send('launcher:toggle-guide'),
  getAramData: () => ipcRenderer.invoke('data:aram'),
  getItemAdvice: () => ipcRenderer.invoke('data:item-advice'),
  getItemTaxonomy: () => ipcRenderer.invoke('data:item-taxonomy'),
  getRankedItemPurposes: () => ipcRenderer.invoke('data:ranked-item-purposes'),
  getChampionBuildProfiles: () => ipcRenderer.invoke('data:champion-build-profiles'),
  getRankedItemGroups: () => ipcRenderer.invoke('data:ranked-item-groups'),
  getBuildRecommendations: (payload) => ipcRenderer.invoke('build:recommend', payload),
  getRiotDiagnostics: () => ipcRenderer.invoke('riot:diagnostics'),
  getLcuState: () => ipcRenderer.invoke('lcu:state'),
  setLcuEnabled: (enabled) => ipcRenderer.invoke('lcu:set-enabled', enabled === true),
  refreshLiveParticipants: () => ipcRenderer.invoke('live:refresh'),
  selectLivePlayer: (participantIndex) => ipcRenderer.invoke('live:select-player', participantIndex),
  testRiotConnection: (platform) => ipcRenderer.invoke('riot:test-connection', platform),
  getOwnRecentMatches: (input) => ipcRenderer.invoke('riot:own-recent-matches', input),
  exportItemSet: (payload) => ipcRenderer.invoke('item-set:export', payload),
  importItemSet: () => ipcRenderer.invoke('item-set:import'),
  evaluateAramAugments: (payload) => ipcRenderer.invoke('aram:evaluate-augments', payload),
  getDragonData: (resource) => ipcRenderer.invoke('data:dragon', resource),
  getPatchCompatibility: (request) => ipcRenderer.invoke('data:patch-compatibility', request || {}),
  getChampionAbilities: (request) => ipcRenderer.invoke('data:champion-abilities', request),
  getChampionDetails: (request) => ipcRenderer.invoke('data:champion-details', request),
  getAramChampion: (slug, championKey) => ipcRenderer.invoke('aram:champion', slug, championKey),
  getAramAugmentImage: (slug, locale) => ipcRenderer.invoke('aram:augment-image', slug, locale),
  getOpggMatchup: (params) => ipcRenderer.invoke('opgg:matchup', params),
  getOpggChampionAnalysis: (params) => ipcRenderer.invoke('opgg:champion-analysis', params),
  onOverlayData: (callback) => ipcRenderer.on('overlay:data', (_event, data) => callback(data)),
  onOverlayInteractionState: (callback) => ipcRenderer.on('overlay:interaction-state', (_event, active) => callback(active === true)),
  onLcuState: (callback) => ipcRenderer.on('lcu:state', (_event, state) => callback(state))
});
